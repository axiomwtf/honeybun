fn main() {
    // Link the CLI binaries as non-PIE (LSB executable). PIE costs ~0.4ms of
    // startup on every invocation in the dev loop, which is the whole point
    // of this binary. Proc-macro and build-script artifacts are host dylibs
    // and are NOT affected (this is not RUSTFLAGS).
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
        // -no-pie: static executable, no GOT/PLT setup, no ASLR page faults
        // per mapping on the hot exec path (see .cargo/config.toml).
        println!("cargo:rustc-link-arg-bins=-no-pie");
        // Resolve all symbols eagerly: no lazy PLT stubs on first call.
        println!("cargo:rustc-link-arg-bins=-Wl,-z,now");
        // Fewer, larger text segments: fewer page faults during exec.
        println!("cargo:rustc-link-arg-bins=-Wl,-z,noseparate-code");
    }
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos")
        && std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("x86_64")
    {
        // Best effort on x86_64 macOS; newer ld may ignore it. arm64 macs
        // hard-require PIE and get native tuning only.
        println!("cargo:rustc-link-arg-bins=-Wl,-no_pie");
    }

    // Code-cache: embed the V8 context startup snapshot when one has been
    // produced (`honey --internal-mksnapshot`). The blob lives at
    // target/honey_snapshot.bin (profile-independent) because cargo deletes
    // target/<profile> contents freely and the generator binary itself is
    // built from this crate (chicken-and-egg: first build has no blob).
    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    // Track the blob even when absent so its creation triggers a rebuild.
    println!("cargo:rerun-if-changed=target/honey_snapshot.bin");
    let blob = std::path::Path::new(&manifest).join("target/honey_snapshot.bin");
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let gen_file = std::path::Path::new(&out_dir).join("honey_snapshot_gen.rs");
    if blob.exists() {
        let path_str = blob.to_string_lossy().replace('\\', "\\\\");
        std::fs::write(
            &gen_file,
            format!(
                "// Generated by build.rs from target/honey_snapshot.bin — do not edit.\n\
                 #[allow(unused)]\n\
                 pub static BLOB: &[u8] = include_bytes!(\"{}\");\n",
                path_str
            ),
        )
        .unwrap();
    } else {
        std::fs::write(
            &gen_file,
            "// Generated by build.rs — no snapshot present.\n\
             #[allow(unused)]\n\
             pub static BLOB: &[u8] = &[];\n",
        )
        .unwrap();
    }
}
